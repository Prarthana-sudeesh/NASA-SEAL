import { useEffect, useRef } from 'react';
import type { Planet } from '../data/types.ts';
import { useCalm } from '../store/settings.ts';

/** Base colour from equilibrium temperature. */
export function tempPalette(T: number): { base: string; light: string; dark: string; glow: string | null } {
  if (T < 200) return { base: '#7FB8FF', light: '#D8ECFF', dark: '#3C6CC4', glow: null };
  if (T <= 350) return { base: '#3FB8A4', light: '#9BE8C4', dark: '#1D6B6E', glow: null };
  if (T <= 1000) return { base: '#E09A4C', light: '#FFD48A', dark: '#A35A2A', glow: 'rgba(255,170,80,0.35)' };
  if (T <= 2000) return { base: '#E8502C', light: '#FFB070', dark: '#8E1E1E', glow: 'rgba(255,100,60,0.5)' };
  return { base: '#FF8A5C', light: '#FFF2D8', dark: '#C0282C', glow: 'rgba(255,220,180,0.6)' };
}

/** Deterministic pseudo-random from a string seed. */
function seeded(seed: string) {
  let h = 2166136261;
  for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
}

/** Display size: relative to radius, clamped so tiny and giant worlds both read well. */
export function planetPixelSize(radiusEarth: number, base: number) {
  const k = Math.min(1, Math.max(0.55, 0.55 + Math.log10(radiusEarth + 1) * 0.4));
  return Math.round(base * k);
}

/**
 * Procedural planet: banded for gas/ice giants, mottled + cratered for rocky worlds,
 * an outer glow for hot worlds, slow rotation. An illustration generated by the game.
 */
export function PlanetArt({ planet, size = 160, spin = true, label = true }: { planet: Planet; size?: number; spin?: boolean; label?: boolean }) {
  const ref = useRef<HTMLCanvasElement>(null);
  const calm = useCalm();
  const px = planetPixelSize(planet.radiusEarth.value, size);
  useEffect(() => {
    const c = ref.current;
    const ctx = c?.getContext('2d');
    if (!c || !ctx) return;
    const dpr = Math.min(2, window.devicePixelRatio || 1);
    const S = size;
    c.width = S * dpr;
    c.height = S * dpr;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const pal = tempPalette(planet.tempK.value);
    const rand = seeded(planet.id);
    const gas = planet.radiusEarth.value > 1.6 && planet.typeLabel !== 'Probably rocky';
    const r = px / 2 - 6;
    const cx = S / 2;
    const cy = S / 2;
    // Surface texture is drawn on a wide strip that scrolls under a circular mask → rotation.
    const W = Math.ceil(r * 4);
    const H = Math.ceil(r * 2);
    const tex = document.createElement('canvas');
    tex.width = W;
    tex.height = H;
    const t = tex.getContext('2d')!;
    t.fillStyle = pal.base;
    t.fillRect(0, 0, W, H);
    if (gas) {
      const bands = 7 + Math.floor(rand() * 6);
      for (let i = 0; i < bands; i++) {
        const y = (i / bands) * H + rand() * 6;
        const bh = H / bands * (0.4 + rand() * 0.8);
        t.fillStyle = [pal.light, pal.dark, pal.base][i % 3];
        t.globalAlpha = 0.35 + rand() * 0.4;
        t.beginPath();
        t.moveTo(0, y);
        for (let x = 0; x <= W; x += 8) t.lineTo(x, y + Math.sin((x / W) * Math.PI * 4 + i) * 3);
        t.lineTo(W, y + bh);
        t.lineTo(0, y + bh);
        t.fill();
      }
      // a storm spot
      t.globalAlpha = 0.7;
      t.fillStyle = pal.dark;
      t.beginPath();
      t.ellipse(W * (0.2 + rand() * 0.3), H * (0.55 + rand() * 0.2), r * 0.28, r * 0.12, 0, 0, Math.PI * 2);
      t.fill();
      t.beginPath();
      t.ellipse(W * 0.2 + W / 2, H * 0.6, r * 0.2, r * 0.09, 0, 0, Math.PI * 2);
      t.fill();
    } else {
      for (let i = 0; i < 26; i++) {
        t.globalAlpha = 0.25 + rand() * 0.35;
        t.fillStyle = rand() > 0.5 ? pal.light : pal.dark;
        const x = rand() * W;
        const y = rand() * H;
        const rr = r * (0.12 + rand() * 0.35);
        t.beginPath();
        t.ellipse(x, y, rr * 1.4, rr, rand(), 0, Math.PI * 2);
        t.fill();
        if (x < rr * 2) {
          t.beginPath();
          t.ellipse(x + W / 2, y, rr * 1.4, rr, 0, 0, Math.PI * 2);
          t.fill();
        }
      }
      for (let i = 0; i < 14; i++) {
        const x = rand() * (W / 2);
        const y = rand() * H;
        const rr = r * (0.04 + rand() * 0.08);
        for (const dx of [0, W / 2]) {
          t.globalAlpha = 0.5;
          t.fillStyle = pal.dark;
          t.beginPath();
          t.arc(x + dx, y, rr, 0, Math.PI * 2);
          t.fill();
          t.globalAlpha = 0.45;
          t.strokeStyle = pal.light;
          t.lineWidth = 1.5;
          t.beginPath();
          t.arc(x + dx - 0.6, y - 0.6, rr, Math.PI * 0.9, Math.PI * 1.9);
          t.stroke();
        }
      }
      if (planet.lavaSurface) {
        t.globalAlpha = 0.9;
        t.strokeStyle = '#FFE27A';
        t.lineWidth = 2;
        for (let i = 0; i < 9; i++) {
          const y = rand() * H;
          t.beginPath();
          t.moveTo(rand() * W, y);
          for (let k = 0; k < 4; k++) t.lineTo(rand() * W, y + (rand() - 0.5) * 30);
          t.stroke();
        }
      }
    }
    t.globalAlpha = 1;

    // Static layers are drawn once: the glow behind, and the shading + outline on top.
    const layer = () => {
      const l = document.createElement('canvas');
      l.width = S * dpr;
      l.height = S * dpr;
      const g = l.getContext('2d')!;
      g.scale(dpr, dpr);
      return { l, g };
    };
    const back = layer();
    if (pal.glow) {
      const g = back.g.createRadialGradient(cx, cy, r * 0.9, cx, cy, r * 1.45);
      g.addColorStop(0, pal.glow);
      g.addColorStop(1, 'rgba(0,0,0,0)');
      back.g.fillStyle = g;
      back.g.fillRect(0, 0, S, S);
    }
    const front = layer();
    {
      const g = front.g;
      g.save();
      g.beginPath();
      g.arc(cx, cy, r, 0, Math.PI * 2);
      g.clip();
      const sh = g.createRadialGradient(cx - r * 0.45, cy - r * 0.45, r * 0.2, cx, cy, r * 1.05);
      sh.addColorStop(0, 'rgba(255,255,255,0.18)');
      sh.addColorStop(0.55, 'rgba(0,0,0,0)');
      sh.addColorStop(1, 'rgba(5,7,15,0.62)');
      g.fillStyle = sh;
      g.fillRect(cx - r, cy - r, r * 2, r * 2);
      g.restore();
      g.lineWidth = 3;
      g.strokeStyle = '#05070F';
      g.beginPath();
      g.arc(cx, cy, r, 0, Math.PI * 2);
      g.stroke();
    }

    let off = rand() * (W / 2);
    let raf = 0;
    let last = performance.now();
    let acc = 0;
    let visible = true;
    const animate = spin && !calm;
    const paint = () => {
      ctx.setTransform(1, 0, 0, 1, 0, 0);
      ctx.clearRect(0, 0, c.width, c.height);
      ctx.drawImage(back.l, 0, 0);
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.save();
      ctx.beginPath();
      ctx.arc(cx, cy, r - 0.5, 0, Math.PI * 2);
      ctx.clip();
      ctx.drawImage(tex, -off, cy - r, W, H);
      ctx.drawImage(tex, -off + W / 2, cy - r, W, H);
      ctx.restore();
      ctx.setTransform(1, 0, 0, 1, 0, 0);
      ctx.drawImage(front.l, 0, 0);
    };
    const draw = (now: number) => {
      raf = requestAnimationFrame(draw);
      const dt = Math.min(0.1, (now - last) / 1000);
      last = now;
      acc += dt;
      if (acc < 1 / 24 || !visible || document.hidden) return; // a slow spin needs ~24 fps
      off = (off + acc * r * 0.12) % (W / 2);
      acc = 0;
      paint();
    };
    paint();
    let io: IntersectionObserver | null = null;
    if (animate) {
      raf = requestAnimationFrame(draw);
      io = new IntersectionObserver(([e]) => (visible = e.isIntersecting));
      io.observe(c);
    }
    return () => {
      cancelAnimationFrame(raf);
      io?.disconnect();
    };
  }, [planet, size, px, spin, calm]);

  return (
    <figure className="m-0 flex flex-col items-center">
      <canvas
        ref={ref}
        style={{ width: size, height: size }}
        role="img"
        aria-label={`Illustration of ${planet.nickname}, generated by the game (not an image of the planet)`}
      />
      {label && <figcaption className="mt-1 max-w-[16rem] text-center text-xs leading-tight text-muted">Illustration generated by the game, not an image of the planet.</figcaption>}
    </figure>
  );
}
